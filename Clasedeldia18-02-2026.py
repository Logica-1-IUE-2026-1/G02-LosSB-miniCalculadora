#Inicio
const = 6
var = int(input("escribe la variable"))
result = var + const
print (f"la suma de {const} + {var} es igual a {result}")
result2 = result - const
print (f"la resta de {result} - {const} es igual a {result2}")
result3 = result2 * const
print (f"la multiplicación de {result2} * {const} es igual a {result3}")
result4 = result3 / const
print (f"la división de {result3} / {const} es igual a {result4}")
result5 = result4 // const
print (f"la división entera de {result4} // {const} es igual a {result5}")
result6 = result5 % const
print (f"el modulo de {result5} % {const} es igual a {result6}")
result7 = result6 ** const
print (f"la potencia de {result6} ** {const} es igual a {result7}")
#fin